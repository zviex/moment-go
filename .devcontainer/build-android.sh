#!/usr/bin/env bash
# 交叉编译 Android (arm64) 目标，并生成可直接交付给 Android 项目的 bundle。
#
# 产物包含：
#   - 可执行文件：<bundle>/app
#   - JNI 原生库：<bundle>/jniLibs/arm64-v8a/*.so
#   - libgphoto2 插件目录：<bundle>/files/libgphoto2/... 与 files/libgphoto2_port/...
#
# 依赖容器/环境内已配置（见 .devcontainer/Dockerfile 的 ENV）：
#   ANDROID_NDK_HOME / ANDROID_API_LEVEL
#
# 用法：
#   bash .devcontainer/build-android.sh [输出目录，默认 bin/app-android-arm64-bundle]
set -euo pipefail

NDK="${ANDROID_NDK_HOME:-/opt/android-ndk}"
API="${ANDROID_API_LEVEL:-27}"
CC="${NDK}/toolchains/llvm/prebuilt/linux-x86_64/bin/aarch64-linux-android${API}-clang"
OUTDIR="${1:-bin/app-android-arm64-bundle}"
OUT="${OUTDIR}/app"

if [ ! -x "${CC}" ]; then
  echo "error: NDK clang not found: ${CC}" >&2
  echo "hint: 检查 ANDROID_NDK_HOME / ANDROID_API_LEVEL 是否正确" >&2
  exit 1
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LIBROOT="${ROOT}/libgphoto2-android"
JNICALL="${LIBROOT}/jniLibs/arm64-v8a"
CAMLIBSRC="${LIBROOT}/lib/libgphoto2"
IOLIBSRC="${LIBROOT}/lib/libgphoto2_port"

cd "${ROOT}"
mkdir -p "${OUTDIR}/jniLibs/arm64-v8a" "${OUTDIR}/files/libgphoto2/2.5.34.1" "${OUTDIR}/files/libgphoto2_port/0.12.2"

GOOS=android GOARCH=arm64 CGO_ENABLED=1 CC="${CC}" \
  go build -o "${OUT}" ./app

# 复制可直接打包到 APK 的 JNI 库
if [ -d "${JNICALL}" ]; then
  cp -L "${JNICALL}"/*.so "${OUTDIR}/jniLibs/arm64-v8a/"
fi

# 复制 libgphoto2 运行时插件目录（Bootstrap 需要的 CAMLIBS/IOLIBS 路径）
if [ -d "${CAMLIBSRC}" ]; then
  cp -a "${CAMLIBSRC}"/. "${OUTDIR}/files/libgphoto2/2.5.34.1/"
fi
if [ -d "${IOLIBSRC}" ]; then
  cp -a "${IOLIBSRC}"/. "${OUTDIR}/files/libgphoto2_port/0.12.2/"
fi

# 兼容性：在输出目录中保留一个直接可复制的二进制路径。
# 这样调用方可以直接把整个 OUTDIR 复制到 Android 项目中，不需要再手工下载任何额外内容。
cat > "${OUTDIR}/README.txt" <<EOF
Android bundle generated by .devcontainer/build-android.sh

Structure:
  app                          -> Android arm64 Go executable
  jniLibs/arm64-v8a/*.so       -> native libraries for APK packaging
  files/libgphoto2/...         -> libgphoto2 camlib plugins
  files/libgphoto2_port/...    -> libgphoto2 iolib plugins

Copy this entire directory into your Android project packaging resources,
then package jniLibs/arm64-v8a under app/src/main/jniLibs/arm64-v8a/
and extract the files/libgphoto2* tree under your app's writable files directory.
EOF

echo "built: ${OUT}"
echo "bundle: ${OUTDIR}"
echo "android bundle ready: copy the whole directory into your Android project packaging flow"
